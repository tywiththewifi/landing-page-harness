#!/usr/bin/env -S npx tsx
/**
 * helm-study audit   Read stripe.com: Helm's stylesheets, which pages run on Helm, and
 *                    the live buttons and links. Writes data/*.json. Needs the network.
 * helm-study build   From data/: the token file, the reports, the docs page and the
 *                    manifest for agents. Offline.
 */
import { mkdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { auditSite, launch } from "./adoption.ts";
import { buildTokens, COMPONENT_TOKENS, tokensCss } from "./build-tokens.ts";
import { DATA, loadAdoption, loadGraph, loadLive, ROOT, toJson, write } from "./data.ts";
import { docsHtml } from "./docs.tsx";
import { HELM_TARGETS, LEGACY_TARGETS, measure } from "./measure.ts";
import { adoptionMarkdown, migrationMarkdown, tokensMarkdown } from "./report.ts";
import { PAIRS } from "./pairs.ts";
import { STORIES } from "./stories.tsx";
import { analyze, parseTokens } from "./tokens.ts";

const ORIGIN = "https://stripe.com";
const UA = { "user-agent": "Mozilla/5.0 (compatible; softlander-helm-study)" };


async function audit() {
  const takenAt = new Date().toISOString();
  console.error("• Reading Helm's stylesheets");
  const home = await (await fetch(ORIGIN + "/", { headers: UA })).text();
  const urls = [...new Set([...home.matchAll(/<link[^>]+rel="stylesheet"[^>]+href="([^"]+\.css)"/g)].map((m) => m[1]!))];
  const files = await Promise.all(urls.map(async (u) => (await fetch(u, { headers: UA })).text()));
  const graph = parseTokens(files, { prefix: "--hds-", darkClass: ".hds-mode--dark", lightClass: ".hds-mode--light" });
  write("helm-tokens.json", { takenAt, source: `${urls.length} stylesheets loaded by ${ORIGIN}/`, data: toJson(graph) });

  console.error("• Checking which pages run on Helm");
  const pages = await auditSite(ORIGIN, undefined, (p) => console.error(`  ${p}`));
  write("adoption.json", { takenAt, source: ORIGIN, data: pages });

  console.error("• Measuring live buttons and links");
  const browser = await launch();
  try {
    const page = await (await browser.newContext({ viewport: { width: 1280, height: 900 } })).newPage();
    await page.goto(ORIGIN + "/", { waitUntil: "networkidle", timeout: 60000 });
    const helm = await measure(page, "/", HELM_TARGETS);
    await page.goto(ORIGIN + "/payments", { waitUntil: "networkidle", timeout: 60000 });
    const legacy = await measure(page, "/payments", LEGACY_TARGETS);
    write("live-components.json", { takenAt, source: ORIGIN, data: [...helm, ...legacy] });
  } finally {
    await browser.close();
  }
  console.error(`\nWrote ${DATA}`);
}

function build() {
  const { graph, takenAt, source } = loadGraph();
  const adoption = loadAdoption().data;
  const live = loadLive().data;
  const tokens = buildTokens(graph);
  const report = analyze(graph, PAIRS);
  const files = Number(/^\d+/.exec(source)?.[0] ?? 0);

  writeFileSync(join(ROOT, "src/components/tokens.css"), tokensCss(tokens, `Helm's tokens as served by stripe.com on ${takenAt.slice(0, 10)}`));
  mkdirSync(join(ROOT, "report"), { recursive: true });
  writeFileSync(join(ROOT, "report/adoption.md"), adoptionMarkdown(adoption, takenAt));
  writeFileSync(join(ROOT, "report/tokens.md"), tokensMarkdown(report, takenAt, files));
  writeFileSync(join(ROOT, "report/migration.md"), migrationMarkdown(live));
  writeFileSync(join(ROOT, "report/tokens-report.json"), JSON.stringify(report, null, 1) + "\n");

  mkdirSync(join(ROOT, "docs"), { recursive: true });
  writeFileSync(join(ROOT, "docs/index.html"), docsHtml({ tokens, adoption, report, takenAt }));
  writeFileSync(join(ROOT, "docs/components.json"), JSON.stringify(manifest(tokens), null, 1) + "\n");
  console.error("Wrote src/components/tokens.css, report/, docs/index.html and docs/components.json");
}

/** What an agent needs to use the components without reading their source. */
function manifest(tokens: ReturnType<typeof buildTokens>) {
  return {
    $comment: "Unofficial study of Helm, generated by @lph/helm-study. Read this before writing markup with these components.",
    stylesheets: ["src/components/tokens.css", "src/components/components.css"],
    modes: { light: "default, or class sl-mode-light on a wrapper", dark: "class sl-mode-dark on a wrapper" },
    components: {
      Button: {
        import: "import { Button } from '@lph/helm-study'",
        props: {
          variant: { type: ["primary", "secondary"], default: "primary", rule: "one primary per view" },
          size: { type: ["default", "compact"], default: "default", rule: "compact only in navigation and dense rows" },
          href: { type: "string", rule: "set it for navigation (renders <a>); leave it out for actions (renders <button>)" },
          arrow: { type: "boolean", default: "true with href, false without" },
          disabled: { type: "boolean", rule: "buttons only; for links use aria-disabled" },
        },
        avoid: ["two primary buttons side by side", "custom colours via style or className: use a variant or ask for a new token"],
      },
      Link: {
        import: "import { Link } from '@lph/helm-study'",
        props: {
          variant: { type: ["inline", "callout"], default: "inline", rule: "callout stands alone with the arrow; inline is inside a sentence and stays underlined" },
          href: { type: "string", required: true },
        },
      },
    },
    examples: STORIES.map((s) => ({ id: s.id, component: s.component, title: s.title, mode: s.mode })),
    tokens: Object.fromEntries(tokens.filter((t) => t.tier === "component").map((t) => [t.name, { mirrors: COMPONENT_TOKENS[t.name], light: t.resolved.light, dark: t.resolved.dark }])),
  };
}

const cmd = process.argv[2];
if (cmd === "audit") await audit();
else if (cmd === "build") build();
else {
  console.error("Usage: helm-study audit | build");
  process.exit(1);
}
