// Writes src/runtime/sources.ts: the form endpoint's source files as strings, so the
// publisher can copy them into a site in Node and in the browser alike.
// Run after changing @lph/forms or src/runtime/handler.ts: pnpm --filter @lph/publisher sync-runtime
import { readFile, writeFile } from "node:fs/promises";

const forms = new URL("../../forms/src/", import.meta.url);
const runtime = new URL("../src/runtime/", import.meta.url);

export async function runtimeSources(): Promise<string> {
  const files: Record<string, string> = {};
  for (const name of ["index.ts", "fields.ts", "submission.ts", "deliver.ts"]) files[`forms/${name}`] = await readFile(new URL(name, forms), "utf8");
  files["handler.ts"] = (await readFile(new URL("handler.ts", runtime), "utf8")).replace(/from "@lph\/forms"/g, 'from "./forms/index.ts"');
  return `// Generated by scripts/sync-runtime.ts from packages/forms/src and src/runtime/handler.ts. Don't edit.\nexport const RUNTIME_FILES: Record<string, string> = ${JSON.stringify(files, null, 2)};\n`;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  await writeFile(new URL("sources.ts", runtime), await runtimeSources());
  console.log("Wrote src/runtime/sources.ts");
}
